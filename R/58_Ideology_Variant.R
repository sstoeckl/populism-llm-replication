chk <- d |> select(doc_id, party, countryname) |> left_join(meta, by = "doc_id")
stopifnot("baseline FE variables must equal the MPDS meta file" =
            all(chk$party == chk$party_meta) && all(chk$countryname == chk$country_meta))

cl <- load_chunk_dims(PIPE_IN, PIPE_DERIVED)
wl <- aggregate_within(cl, validation = "quote") |>
  filter(dim %in% c("pop_ideology_right", "pop_ideology_left"))
rl <- wl |> select(doc_id, model, dim, cwm) |>
  mutate(dim = recode(dim, pop_ideology_right = "R", pop_ideology_left = "L")) |>
  pivot_wider(names_from = dim, values_from = cwm)
# full doc x model grid: a model without any verified R/L chunk has no row in wl
grid_dm <- expand_grid(doc_id = d$doc_id, model = AGG_MODELS) |>
  left_join(rl, by = c("doc_id", "model")) |> arrange(doc_id, model)

# check: within-model scores equal the per-model columns of the baseline file
for (m in AGG_MODELS) {
  g <- grid_dm |> filter(model == m) |> left_join(d |> select(doc_id, bR = paste0("pop_ideology_right_", m),
                                                               bL = paste0("pop_ideology_left_", m)), by = "doc_id")
  stopifnot(isTRUE(all.equal(g$R, g$bR)), isTRUE(all.equal(g$L, g$bL)))
}
logf("within-model R and L reproduced from load_chunk_dims/aggregate_within; equal to the baseline per-model columns")

# ---- 2. Baseline and variants ------------------------------------------------------------------
gz <- grid_dm |>
  mutate(contrib = !is.na(R) | !is.na(L),               # model contributes to the manifesto's ideology
         Rz = ifelse(contrib, coalesce(R, 0), NA_real_),
         Lz = ifelse(contrib, coalesce(L, 0), NA_real_),
         ideo_m = ideo_direction(Rz, Lz))
per_doc <- gz |> group_by(doc_id) |>
  summarise(n_models_R = sum(!is.na(R)), n_models_L = sum(!is.na(L)),
            n_models_contrib = sum(contrib), n_models_v1 = sum(!is.na(ideo_m)),
            R_mean = if (any(!is.na(R))) mean(R, na.rm = TRUE) else NA_real_,
            L_mean = if (any(!is.na(L))) mean(L, na.rm = TRUE) else NA_real_,
            Rz_mean = if (any(contrib)) mean(Rz, na.rm = TRUE) else NA_real_,
            Lz_mean = if (any(contrib)) mean(Lz, na.rm = TRUE) else NA_real_,
            IDEO_v1 = if (any(!is.na(ideo_m))) mean(ideo_m, na.rm = TRUE) else NA_real_,
            .groups = "drop") |>
  mutate(IDEO_base = ideo_direction(R_mean, L_mean),
         IDEO_v2   = ideo_direction(Rz_mean, Lz_mean))

dd <- d |> select(doc_id, countryname, party, year, populism_overall, all_of(names(DVS)),
                  pop_ideology_direction, pop_ideology_right, pop_ideology_left,
                  n_models_pop_ideology_right, n_models_pop_ideology_left) |>
  left_join(per_doc, by = "doc_id")
stopifnot("recomputed baseline IDEO must equal the baseline file" =
            isTRUE(all.equal(dd$IDEO_base, dd$pop_ideology_direction)),
          isTRUE(all.equal(dd$R_mean, dd$pop_ideology_right)), isTRUE(all.equal(dd$L_mean, dd$pop_ideology_left)),
          all(dd$n_models_R == coalesce(dd$n_models_pop_ideology_right, 0L)),   # one manifesto (no verified chunk in any model) has NA counts
          all(dd$n_models_L == coalesce(dd$n_models_pop_ideology_left, 0L)),
          # both variants are defined wherever the baseline is (null-as-zero only adds information)
          all(!is.na(dd$IDEO_v1[!is.na(dd$IDEO_base)])), all(!is.na(dd$IDEO_v2[!is.na(dd$IDEO_base)])),
          all(abs(dd$IDEO_v1) <= 1 + 1e-12, na.rm = TRUE), all(abs(dd$IDEO_v2) <= 1 + 1e-12, na.rm = TRUE))
