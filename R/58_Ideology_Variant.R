# ============================================================
# 58_Ideology_Variant.R   (stage `ideovar`, to be added to run_all.R)
#
# Online-appendix variant of the ideology measure (PLLM-0245, review 2026-11-11 EMP-005 / MATH-003;
# computed before submission, decided by Sebastian 2026-11-11). No API calls.
#
# Problem with the baseline IDEO = (R - L) / (R + L) on the cross-model means (R/1_Aggregation.R):
#   (i)  IDEO is NA when R or L is missing across all models, although a missing R means that no
#        model found verified right-wing content, whose natural value is 0 (IDEO = -1);
#   (ii) R and L are averaged over different model sets within a manifesto (Gemini's R is missing
#        for about two thirds of the manifestos), so the ratio mixes models.
#
# Variant construction (per manifesto, per model m; R_m, L_m = within-model confidence-weighted
# means of R/1_Aggregation.R, canonical rule (a'), validation "quote"):
#   null-as-zero:  if exactly one of R_m, L_m is null, set the null one to 0; if both are null,
#                  model m does not contribute to the manifesto's ideology.
#   V1 (IDEO_v1)  = mean over the contributing models of (R_m* - L_m*) / (R_m* + L_m*)
#                   (ratio within model, then plain mean across models; a model with
#                   R_m* + L_m* = 0 drops out).
#   V2 (IDEO_v2)  = (Rbar* - Lbar*) / (Rbar* + Lbar*), Rbar*, Lbar* = plain means of R_m*, L_m*
#                   over the same contributing models (ratio on cross-model means, null-as-zero).
# Both variants use one model set for R and L. The baseline IDEO is recomputed from the same
# functions and checked against the baseline file (stopifnot).
#
# Regressions: columns (2)-(7) of Tables 4-8 (R/41 fit_six) for the five outcomes, with the
# baseline IDEO and with each variant; each column on its own complete cases; SE clustered by
# CMP party code; p-values from t(G - 1) (fixest default for clustered SE). Marginal effects of
# POP in columns (5) and (7) at the 10th percentile, median and 90th percentile of each measure
# over all manifestos (as R/41's me_curve, which uses the quantiles of IDEO over all manifestos).
#
# Inputs : data/CMP/v2026a chunk files via load_chunk_dims() (R/1_Aggregation.R, unmodified),
#          PIPE_DERIVED/manifesto_scores_v2026a.parquet (sample, outcomes, POP, FE variables),
#          PIPE_META (cross-check of party / country codes).
# Outputs: PIPE_OUT/csv/58_ideo_variant_scores.csv       doc_id, baseline IDEO, V1, V2, model counts
#          PIPE_OUT/csv/58_ideo_variant_regressions.csv  long: variant, outcome, model, term, ...
#          PIPE_OUT/tables/oa_ideo_variant_regs.tex      tab:oa2g (cols (4), (5), (7))
#          PIPE_OUT/tables/oa_ideo_variant_coverage.tex  tab:oa2h (re-entering manifestos)
#          PIPE_OUT/logs/58_ideo_variant.txt
# ============================================================

