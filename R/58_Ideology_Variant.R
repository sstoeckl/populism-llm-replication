fit_cols <- function(dv, iv, data) {
  f <- function(rhs, fe) as.formula(paste(dv, "~", rhs, "|", fe))
  dat <- data |> mutate(IDEO = .data[[iv]])
  list(m2 = feols(f("IDEO", "countryname + year"), data = dat, cluster = ~party),
       m3 = feols(f("populism_overall + IDEO", "countryname"), data = dat, cluster = ~party),
       m4 = feols(f("populism_overall + IDEO", "countryname + year"), data = dat, cluster = ~party),
       m5 = feols(f("populism_overall * IDEO", "countryname + year"), data = dat, cluster = ~party),
       m6 = feols(f("populism_overall + IDEO", "countryname + year + party"), data = dat, cluster = ~party),
       m7 = feols(f("populism_overall * IDEO", "countryname + year + party"), data = dat, cluster = ~party))
}
me_at <- function(m, at_vals, G) {   # R/41 me_curve, party-clustered vcov, t(G - 1)
  b <- coef(m); V <- vcov(m); i1 <- "populism_overall"; i3 <- "populism_overall:IDEO"
  me <- b[[i1]] + b[[i3]] * at_vals
  se <- sqrt(V[i1, i1] + at_vals^2 * V[i3, i3] + 2 * at_vals * V[i1, i3])
  tibble(term = paste0("ME_POP_at_", names(at_vals)), at_value = unname(at_vals), estimate = unname(me),
         se = unname(se), t = estimate / se, p = 2 * pt(-abs(t), df = G - 1))
}
regs <- map_dfr(names(VARIANTS), function(v) {
  iv <- VAR_COL[[v]]
  q <- quantile(dd[[iv]], c(.1, .5, .9), na.rm = TRUE, names = FALSE) |> set_names(c("p10", "p50", "p90"))
  map_dfr(names(DVS), function(dv) {
    ms <- fit_cols(dv, iv, dd)
    imap_dfr(ms, function(m, mn) {
      G <- n_distinct(dd$party[obs(m)])
      ct <- coeftable(m)
      out <- tibble(term = rownames(ct), at_value = NA_real_, estimate = ct[, 1], se = ct[, 2], t = ct[, 3], p = ct[, 4])
      if (mn %in% c("m5", "m7")) out <- bind_rows(out, me_at(m, q, G))
      out |> mutate(variant = v, outcome = dv, model = mn, nobs = nobs(m), n_clusters = G, .before = 1)
    })
  })
}) |> select(variant, outcome, model, term, at_value, estimate, se, t, p, nobs, n_clusters)
write_csv_det(regs, file.path(CSV, "58_ideo_variant_regressions.csv"))

