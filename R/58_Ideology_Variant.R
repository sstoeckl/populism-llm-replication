# ---- 1. Within-model R and L from the canonical aggregation ------------------------------------
d <- read_parquet(file.path(PIPE_DERIVED, "manifesto_scores_v2026a.parquet"))
stopifnot(nrow(d) == 3371L, !anyDuplicated(d$doc_id), all(d$validation_rule == "quote"))
