MEANVARS <- c("populism_overall", names(DVS))
grp_means <- dd |> mutate(group = ifelse(reenter, "reenter", "rest")) |> group_by(group) |>
  summarise(n = n(), across(all_of(MEANVARS), ~ mean(.x, na.rm = TRUE)), .groups = "drop")
# Welch t-test of the difference re-entering vs rest
grp_tests <- map_dfr(MEANVARS, function(v) {
  tt <- t.test(dd[[v]][dd$reenter], dd[[v]][!dd$reenter])
  tibble(var = v, mean_reenter = unname(tt$estimate[1]), mean_rest = unname(tt$estimate[2]),
         diff = unname(tt$estimate[1] - tt$estimate[2]), p_welch = tt$p.value)
})
