dist_of <- function(x) tibble(n = sum(!is.na(x)), mean = mean(x, na.rm = TRUE),
  q10 = quantile(x, .1, na.rm = TRUE, names = FALSE), q50 = quantile(x, .5, na.rm = TRUE, names = FALSE),
  q90 = quantile(x, .9, na.rm = TRUE, names = FALSE),
  share_m1 = mean(abs(x + 1) < 1e-9, na.rm = TRUE), share_p1 = mean(abs(x - 1) < 1e-9, na.rm = TRUE))
dist <- bind_rows(
  dist_of(dd$IDEO_v1[dd$reenter]) |> mutate(group = "reenter", measure = "v1"),
  dist_of(dd$IDEO_v2[dd$reenter]) |> mutate(group = "reenter", measure = "v2"),
  dist_of(dd$IDEO_base) |> mutate(group = "rest", measure = "base"),
  dist_of(dd$IDEO_v1[!dd$reenter]) |> mutate(group = "rest", measure = "v1"),
  dist_of(dd$IDEO_v2[!dd$reenter]) |> mutate(group = "rest", measure = "v2")) |>
  relocate(group, measure)
