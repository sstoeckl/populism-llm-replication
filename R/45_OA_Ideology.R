# ---- C2. Errors in variables: one model's populism instrumented by another's (tab:oa4b; PLLM-0248) ------
# EMP-002: a noisy regressor is attenuated more within parties, where little true variation is left.
# Classical-measurement-error check: overall liberalism (cross-model mean, as in Tables 4-8) on the
# populism score of ONE model (x), instrumented by the populism score of ANOTHER model (z); all six
# ordered pairs; country + year FE and country + year + party FE; SE clustered by party (CMP code).
# OLS of the same single-model regressor on the same sample next to it. If the two models' errors are
# independent of each other and of the outcome's error, b_IV is consistent and b_OLS / b_IV estimates
# the reliability of x conditional on the fixed effects. Caveat (shared-call halo): the outcome
# contains the liberalism score of the instrument model, scored in the same call as its populism;
# a halo in that model would move b_IV away from zero. A variant whose outcome is the liberalism
# score of the THIRD model (neither x nor z) is in the csv (columns *_y3).
EIV_FE <- c(cy = "countryname + year", cyp = "countryname + year + party")
eiv_pairs <- expand_grid(x = names(MODELS), z = names(MODELS)) |> filter(x != z)
eiv <- pmap_dfr(eiv_pairs, function(x, z) map_dfr(names(EIV_FE), function(fe) {
  px <- paste0("populism_overall_", x); pz <- paste0("populism_overall_", z)
  y3 <- paste0("liberalism_overall_", setdiff(names(MODELS), c(x, z)))
  fit <- function(y) {
    dd <- d |> filter(!is.na(.data[[y]]), !is.na(.data[[px]]), !is.na(.data[[pz]]))
    mo <- feols(as.formula(paste(y, "~", px, "|", EIV_FE[[fe]])), dd, cluster = ~party)
    mi <- feols(as.formula(paste(y, "~ 1 |", EIV_FE[[fe]], "|", px, "~", pz)), dd, cluster = ~party)
    fs <- fitstat(mi, "ivwald1", simplify = TRUE)   # first-stage Wald F, party-clustered vcov
    term <- paste0("fit_", px)
    list(b_ols = coef(mo)[[px]], se_ols = se(mo)[[px]], b_iv = coef(mi)[[term]], se_iv = se(mi)[[term]],
         p_iv = pvalue(mi)[[term]], fs_F = unname(fs$stat), n = nobs(mi), n_clusters = n_distinct(dd$party[obs(mi)]))
  }
  a <- fit("liberalism_overall"); b <- fit(y3)
  tibble(x = x, z = z, fe = fe, b_ols = a$b_ols, se_ols = a$se_ols, b_iv = a$b_iv, se_iv = a$se_iv, p_iv = a$p_iv,
         first_stage_F = a$fs_F, reliability = a$b_ols / a$b_iv, n = a$n, n_clusters = a$n_clusters,
         y3 = y3, b_ols_y3 = b$b_ols, b_iv_y3 = b$b_iv, se_iv_y3 = b$se_iv, reliability_y3 = b$b_ols / b$b_iv, n_y3 = b$n)
}))
