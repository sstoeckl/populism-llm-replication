# Layout: the tabular sits in a guarded \resizebox that shrinks it only if it is wider than the
# text (graphicx; loaded by main.tex); the note goes below the tabular, at full text width. The
# note text is carried by note_row() and placed by tab_close().
note_row <- function(ncol, txt) paste0("%%NOTE%%", txt)
tab_open <- function(caption, label, spec, size = "\\footnotesize")
  c("\\begin{table}[ht]", sprintf("\\caption{%s}", caption), sprintf("\\label{%s}", label), size, "\\centering",
    "\\resizebox{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}{!}{%",
    sprintf("\\begin{tabular}{%s}", spec), "\\toprule")
tab_close <- c("\\end{tabular}}", "\\end{table}")
write_tex <- function(lines, file) {
  k <- grep("^%%NOTE%%", lines)
  if (length(k)) {
    note <- sub("^%%NOTE%%", "", lines[k]); lines <- lines[-k]
    e <- max(grep("^\\\\end\\{table\\}$", lines))
    lines <- append(lines, c("\\par\\smallskip", sprintf("\\begin{minipage}{\\linewidth}\\scriptsize %s\\end{minipage}", note)), after = e - 1)
  }
  write_atomic(lines, file.path(TAB, file), writer = function(x, p) writeLines(x, p, useBytes = TRUE))
}
