reg <- map_dfr(names(DVS), function(dv) {
  map_dfr(IVS, function(iv) {
    ivs <- str_split(iv, " \\+ ")[[1]]; main <- ivs[1]
    dd <- dz |> filter(if_all(all_of(c(dv, "populism_overall", ivs)), ~ !is.na(.x)))
    f4 <- as.formula(paste(dv, "~ populism_overall +", paste(ivs, collapse = " + "), "| countryname + year"))
    f5 <- as.formula(paste(dv, "~ populism_overall *", main, if (length(ivs) > 1) paste("+", ivs[-1]) else "", "| countryname + year"))
    f4z <- as.formula(paste(dv, "~ populism_overall +", paste(paste0("z_", ivs), collapse = " + "), "| countryname + year"))
    m4 <- feols(f4, dd, cluster = ~party); m5 <- feols(f5, dd, cluster = ~party); m4z <- feols(f4z, dd, cluster = ~party)
    ct4 <- coeftable(m4); ct5 <- coeftable(m5); ct4z <- coeftable(m4z)
    inter <- paste0("populism_overall:", main)
    tibble(dv = dv, iv = iv, n = nobs(m4), n_clusters = n_distinct(dd$party[obs(m4)]),
           b_pop_m4 = ct4["populism_overall", 1], se_pop_m4 = ct4["populism_overall", 2], p_pop_m4 = ct4["populism_overall", 4],
           b_ideo_m4 = ct4[main, 1], se_ideo_m4 = ct4[main, 2], p_ideo_m4 = ct4[main, 4],
           b_ideo_m4_std = ct4z[paste0("z_", main), 1],
           b_C_m4 = if ("C" %in% ivs) ct4["C", 1] else NA_real_, se_C_m4 = if ("C" %in% ivs) ct4["C", 2] else NA_real_,
           p_C_m4 = if ("C" %in% ivs) ct4["C", 4] else NA_real_,
           b_C_m4_std = if ("C" %in% ivs) ct4z["z_C", 1] else NA_real_,
           b_inter_m5 = ct5[inter, 1], se_inter_m5 = ct5[inter, 2], p_inter_m5 = ct5[inter, 4],
           b_pop_m5 = ct5["populism_overall", 1],
           # marginal effect of POP at the 10% / 90% quantile of the ideology measure
